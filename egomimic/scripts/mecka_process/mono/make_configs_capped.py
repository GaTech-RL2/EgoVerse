"""Write capped-hours-per-operator variants of the fold_tshirt operator-scaling configs.

Each operator's train pool (as in mecka_private_tshirt_opscale_*) is capped at CAP
minutes: a seeded shuffle of its train episodes, taken in order until the next one
would pass the cap. The shuffle does not depend on the cap, so a smaller cap's picks
are a prefix of a larger one's, and every scale uses the same episodes of the
operators it shares. The train_viz video pin is forced into operator 1's pick.
IDs go to $EGOVERSE_MECKA_PRIVATE_DIR/splits (private_ids.py).

  python -m egomimic.scripts.mecka_process.mono.make_configs_capped {30m,2h}
"""

import json
import random
import sys
from pathlib import Path

from egomimic.scripts.mecka_process.mono.private_ids import private_dir, write_config

PRIV = private_dir()
HERE = PRIV / "scaling"
SPLITS = PRIV / "splits"
CFG = Path(__file__).resolve().parents[3] / "hydra_configs"
SEED = 0
# minutes per operator, 100-step epochs and val cadence (epochs) per scale.
VARIANTS = {
    "30m": dict(
        minutes=30,
        epochs={1: 250, 3: 300, 6: 350, 10: 450},
        val_every={1: 5, 3: 10, 6: 10, 10: 10},
    ),
    "2h": dict(
        minutes=120,
        epochs={1: 250, 3: 400, 6: 550, 10: 700},
        val_every={1: 5, 3: 10, 6: 10, 10: 10},
    ),
}
TAG = sys.argv[1]
V = VARIANTS[TAG]
CAP_FRAMES = V["minutes"] * 60 * 30
EPOCHS, VAL_EVERY = V["epochs"], V["val_every"]


def main() -> None:
    picks = json.load(open(HERE / "opscale_picks.json"))
    index = json.load(open(PRIV / "zarr" / "_episode_index.json"))
    held = {h for v in picks["held_out"].values() for h in v}
    pin = picks["train_viz_pin"]
    chosen, summary = {}, {}
    for op in picks["order"]:
        pool = sorted(
            (h, a["total_frames"])
            for h, a in index.items()
            if a.get("task") == "fold_tshirt"
            and a.get("user_id") == op
            and h not in held
        )
        random.Random(f"{SEED}:{op}").shuffle(pool)
        pool.sort(
            key=lambda p: p[0] != pin
        )  # stable: the pin first, else shuffled order
        total, eps = 0, []
        for h, n in pool:
            if total + n > CAP_FRAMES:
                break
            eps.append(h)
            total += n
        chosen[op] = eps
        summary[op] = {
            "eps": len(eps),
            "frames": total,
            "minutes": round(total / 1800, 1),
        }
    assert pin in chosen[picks["order"][0]]
    json.dump(
        {"cap_frames": CAP_FRAMES, "seed": SEED, "train": chosen, "summary": summary},
        open(HERE / f"opscale_picks_{TAG}.json", "w"),
        indent=1,
    )

    for n in EPOCHS:
        ops = picks["order"][:n]
        hashes = "\n".join(
            f"        - {h}" + (f" # op{i + 1} {op}" if j == 0 else "")
            for i, op in enumerate(ops)
            for j, h in enumerate(chosen[op])
        )
        write_config(
            CFG / f"data/mecka_private_tshirt{TAG}_opscale_{n}.yaml",
            f"""# mecka_private_tshirt_opscale_{n} with each operator's train episodes capped at
# {V['minutes']} min (seeded, nested across scales and caps; picks in opscale_picks_{TAG}.json). The val
# heads are unchanged; train_viz follows the train filter. Generated by
# egomimic/scripts/mecka_process/mono/make_configs_capped.py.
defaults:
  - mecka_private_tshirt_opscale_{n}
  - _self_

train_datasets:
  human_bimanual:
    filters:
      episode_hashes:
{hashes}
""",
            SPLITS,
        )
        e = EPOCHS[n]
        write_config(
            CFG / f"train_zarr_mecka_private_tshirt{TAG}_opscale_{n}.yaml",
            f"""# train_zarr_mecka_private_tshirt_opscale_{n} on the {V['minutes']}-min-per-operator data:
# {e} x 100 steps, val every {VAL_EVERY[n] * 100} steps. WSD LR from the launcher.
# Generated; see data/mecka_private_tshirt{TAG}_opscale_{n}.
defaults:
  - train_zarr_mecka_private_tshirt_opscale_{n}
  - override data: mecka_private_tshirt{TAG}_opscale_{n}
  - _self_

trainer:
  max_epochs: {e}
  min_epochs: {e}
  check_val_every_n_epoch: {VAL_EVERY[n]}

callbacks:
  model_checkpoint:
    every_n_epochs: {e // 5}
""",
            SPLITS,
        )
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
