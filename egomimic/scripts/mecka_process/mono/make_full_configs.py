"""Write the private full-task data + train configs (all operators of one task).

On top of make_configs.py's 10-operator scale (same held-out picks, unseen SQL
head, recipe and epochs), two variants per task:
  <slug>_full         train on all 10 operators; seen_valid = all 50 held-out eps
  <slug>_full_unseen  operator UNSEEN[task] left out of train entirely and scored
                      as a 4th head (unseen_private_valid); seen_valid = the other
                      9 operators' 45 held-out eps

  python -m egomimic.scripts.mecka_process.mono.make_full_configs

UNSEEN comes from scaling/opscale_inputs.json; IDs go to the private splits dir.
"""

import json
from pathlib import Path

from egomimic.scripts.mecka_process.mono.private_ids import private_dir, write_config

PRIV = private_dir()
HERE = PRIV / "scaling"
SPLITS = PRIV / "splits"
CFG = Path(__file__).resolve().parents[3] / "hydra_configs"

# The unseen operator (full_unseen): not in a same-room pair and not one of the
# small/unclean operators.
TASKS = {
    "fold_tshirt": dict(slug="tshirt", picks="opscale_picks.json"),
    "fold_no_tshirt": dict(slug="notshirt", picks="opscale_picks_notshirt.json"),
}


def hash_list(held, ops, indent):
    pad = " " * indent
    lines = []
    for op in ops:
        for i, h in enumerate(held[op]):
            lines.append(f"{pad}- {h}" + (f" # {op}" if i == 0 else ""))
    return "\n".join(lines)


def train_cfg(slug, variant, note):
    src = (CFG / f"train_zarr_mecka_private_{slug}_opscale_10.yaml").read_text()
    body = src[src.index("model:") :]
    return f"""# {note}
# Recipe of train_zarr_mecka_private_{slug}_opscale_10 (RDT-1B keypoints, 4 GPUs x
# 32, EMA, WSD LR passed by the launcher). Generated by make_full_configs.py.
defaults:
  - train_zarr_mecka_freeform_fold_kp_rdt_op2
  - override data: mecka_private_{slug}_{variant}
  - _self_

{body}"""


def base_cfg(slug, variant):
    one_b = (CFG / f"train_zarr_mecka_private_{slug}_{variant}.yaml").read_text()
    epochs = int(one_b.split("max_epochs:")[1].split()[0]) // 2
    return f"""# train_zarr_mecka_private_{slug}_{variant} on the RDT base (DiT 1280 x 18, ~300M;
# + DINOv3 ViT-B, frozen Qwen) instead of RDT-1B, as in the running
# train_zarr_mecka_private_tshirt30m_opscale_base_* arm: global batch 256 = 4 GPUs x 64,
# half the 1B's optimizer steps (same samples), torch.compile. WSD from the launcher.
# Generated by make_full_configs.py.
defaults:
  - train_zarr_mecka_private_{slug}_{variant}
  - override model: rdt_bc_mecka_kp_dinov3_vitb
  - _self_

data:
  train_dataloader_params:
    human_bimanual:
      batch_size: 64

model:
  ema:
    enabled: true
  # 1.37x train speed on 1 H100 at batch 64, loss unchanged
  compile:
    enabled: true
    mode: null
    dynamic: false

trainer:
  max_epochs: {epochs}
  min_epochs: {epochs}

callbacks:
  model_checkpoint:
    every_n_epochs: {epochs // 2}
"""


def main():
    inputs = json.loads((HERE / "opscale_inputs.json").read_text())
    for task, spec in TASKS.items():
        slug, unseen = spec["slug"], inputs[task]["full_unseen"]
        picks = json.loads((HERE / spec["picks"]).read_text())
        order, held = picks["order"], picks["held_out"]
        seen = [op for op in order if op != unseen]

        full = f"""# PRIVATE Mecka mono {task}, full task: all 10 operators minus 5 held-out
# episodes each. Generated by egomimic/scripts/mecka_process/mono/make_full_configs.py.
#   train            = all operators minus held_out_hashes
#   seen_valid       = all 50 held-out episodes (5 per operator)
#   unseen_op_valid  = 5 SQL mecka folding_clothes operators x 5 episodes
defaults:
  - mecka_private_{slug}_opscale_10
  - _self_

valid_prefix: seen_valid

valid_datasets:
  human_bimanual:
    filters:
      episode_hashes: ${{data.held_out_hashes}}

extra_valid_datasets:
  human_bimanual: null
"""
        write_config(CFG / "data" / f"mecka_private_{slug}_full.yaml", full, SPLITS)

        unseen_cfg = f"""# mecka_private_{slug}_full with one operator never trained on and scored as its
# own head (unseen_private_valid: all its episodes). The SQL unseen_op_valid head
# stays. Generated by make_full_configs.py.
defaults:
  - mecka_private_{slug}_full
  - _self_

train_operators:
{chr(10).join(f"  - {op}" for op in seen)}

valid_datasets:
  human_bimanual:
    filters:
      episode_hashes:
{hash_list(held, seen, 8)}

extra_valid_prefix: unseen_private_valid

extra_valid_datasets:
  human_bimanual:
    _target_: ${{data.train_datasets.human_bimanual._target_}}
    resolver: ${{data.train_datasets.human_bimanual.resolver}}
    bounds_rel_slack: 10.0
    filters:
      _target_: egomimic.rldb.filters.DatasetFilter
      filter_lambdas:
        - "lambda row: str(row.get('task', '')) == '{task}'"
        - "lambda row: str(row.get('user_id', '')) == '{unseen}'"
    pose_glitch_mask: {{step_m: 0.05, rot_deg: 10.0}}
    mode: total

video_episodes:
  extra_valid:
    - {held[unseen][0]}
"""
        write_config(
            CFG / "data" / f"mecka_private_{slug}_full_unseen.yaml", unseen_cfg, SPLITS
        )

        for variant, note in (
            ("full", f"Full private {task}: all 10 operators, 5 held out each."),
            (
                "full_unseen",
                f"Full private {task} minus one operator (scored as unseen).",
            ),
        ):
            name = f"train_zarr_mecka_private_{slug}_{variant}.yaml"
            write_config(CFG / name, train_cfg(slug, variant, note), SPLITS)
        for variant in ("full", "full_unseen"):
            name = f"train_zarr_mecka_private_{slug}_{variant}_base.yaml"
            write_config(CFG / name, base_cfg(slug, variant), SPLITS)
        print(task, "seen ops", len(seen), "valid eps", sum(len(held[o]) for o in seen))


if __name__ == "__main__":
    main()
